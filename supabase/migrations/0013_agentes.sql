-- La versión de la estrategia la lleva la base de datos, no quien la
-- edita: un corte semanal, una adopción o un cambio a mano suben el
-- contador igual, y ninguno puede olvidarse.
create function public.fn_versionar_estrategia()
returns trigger
language plpgsql as $$
begin
    if tg_op = 'UPDATE' then
        if (new.estrategia - 'version') is not distinct from (old.estrategia - 'version') then
            new.estrategia := jsonb_set(new.estrategia, '{version}', to_jsonb(old.version_estrategia));
            new.version_estrategia := old.version_estrategia;
            return new;
        end if;
        new.version_estrategia := old.version_estrategia + 1;
    end if;
    new.estrategia := jsonb_set(new.estrategia, '{version}', to_jsonb(new.version_estrategia));
    return new;
end;
$$;

create trigger agentes_versionar_estrategia
    before insert or update of estrategia on public.agentes
    for each row execute function public.fn_versionar_estrategia();

create function public.fn_historico_estrategia()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
    insert into public.agente_estrategia_versiones (agente_id, version, estrategia)
    values (new.id, new.version_estrategia, new.estrategia)
    on conflict do nothing;
    return null;
end;
$$;

create trigger agentes_historico_estrategia
    after insert or update of estrategia on public.agentes
    for each row execute function public.fn_historico_estrategia();

-- Un evento sobre una cuenta de agente se etiqueta con el agente solo.
-- Así `rpc_cerrar_orden`, `rpc_evaluar_fase` y `rpc_evaluar_game_over`
-- —que no saben de agentes y no se tocan— dejan eventos filtrables por
-- agente sin cambiar una línea.
create function public.fn_evento_etiquetar_agente()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
    if new.agente_id is null and new.datos ? 'cuenta_id' then
        select agente_id into new.agente_id
          from public.cuentas_simulacion
         where id = (new.datos ->> 'cuenta_id')::bigint;
    end if;
    return new;
end;
$$;

create trigger eventos_sistema_etiquetar_agente
    before insert on public.eventos_sistema
    for each row execute function public.fn_evento_etiquetar_agente();

