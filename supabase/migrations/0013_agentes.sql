-- La estrategia del agente, completada con valores prudentes por
-- defecto y con las consecuencias del corte semanal aplicadas encima:
-- riesgo a la mitad tras una deficiente, y en cuarentena solo fuerza
-- alta y una posición (doc 03 §6.2).
create function public.fn_parametros_agente(p_agente public.agentes)
returns jsonb
language plpgsql immutable
as $$
declare
    v jsonb;
begin
    v := jsonb_build_object(
            'riesgo_pct_operacion', 2.0,
            'max_posiciones_abiertas', 1,
            'rr_minimo', 1.5,
            'fuerzas_admitidas', jsonb_build_array('alta'),
            'clases_admitidas', jsonb_build_array('accion', 'cripto'),
            'niveles_origen_admitidos', jsonb_build_array('estructura', 'atr'),
            'apalancamiento_maximo_propio', 5.0,
            'margen_comprometido_max_pct', 40.0,
            'atr_pct_min', null,
            'atr_pct_max', null,
            'antiguedad_senal_max_min', 90)
         || (p_agente.estrategia - 'practicas_adoptadas' - 'version' - 'modo_conservacion');

    if p_agente.riesgo_reducido then
        v := jsonb_set(v, '{riesgo_pct_operacion}',
                       to_jsonb(round((v ->> 'riesgo_pct_operacion')::numeric / 2, 2)));
    end if;
    if p_agente.estado = 'cuarentena'
       or (p_agente.estado = 'pausado' and p_agente.estado_previo = 'cuarentena') then
        v := v || jsonb_build_object('max_posiciones_abiertas', 1,
                                     'fuerzas_admitidas', jsonb_build_array('alta'));
    end if;
    return v;
end;
$$;

-- La cuenta viva del agente: la más reciente que no sea un Game Over, o
-- el último Game Over si no hay otra.
create function public.fn_cuenta_agente(p_agente_id bigint)
returns bigint
language sql stable
as $$
    select id from public.cuentas_simulacion
     where agente_id = p_agente_id
     order by (estado <> 'game_over') desc, id desc
     limit 1
$$;

-- Los guardarraíles los impone `rpc_abrir_orden` leyendo la CUENTA, no
-- la estrategia. Esta función es el puente: copia los parámetros
-- efectivos a la cuenta, y los CHECK de `cuentas_simulacion` rechazan una
-- estrategia absurda (un 40 % de riesgo por operación no llega a
-- escribirse). Es lo que hace cierta la frase del doc 03 §4: «una
-- estrategia adoptada con un valor absurdo no puede saltárselos».
create function public.fn_sincronizar_cuenta_agente(p_agente_id bigint)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_ag public.agentes;
    v_p  jsonb;
begin
    select * into v_ag from public.agentes where id = p_agente_id;
    if not found then return; end if;
    v_p := public.fn_parametros_agente(v_ag);

    update public.cuentas_simulacion
       set riesgo_pct_operacion        = (v_p ->> 'riesgo_pct_operacion')::numeric,
           max_posiciones_abiertas     = (v_p ->> 'max_posiciones_abiertas')::int,
           margen_comprometido_max_pct = (v_p ->> 'margen_comprometido_max_pct')::numeric,
           antiguedad_senal_max_min    = (v_p ->> 'antiguedad_senal_max_min')::int,
           ratio_rr_minimo             = (v_p ->> 'rr_minimo')::numeric,
           actualizado_en              = now()
     where agente_id = p_agente_id and estado <> 'game_over';
end;
$$;

create function public.fn_agentes_sincronizar()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
    perform public.fn_sincronizar_cuenta_agente(new.id);
    return null;
end;
$$;

create trigger agentes_sincronizar_cuenta
    after insert or update of estrategia, estado, riesgo_reducido on public.agentes
    for each row execute function public.fn_agentes_sincronizar();

-- ¿Hay mercado para este agente en esta fecha? Cripto cotiza siempre;
-- las acciones, de lunes a viernes (mismo criterio sin festivos que
-- `ventana_mercado.py` y `fn_mercado_abierto`).
create function public.fn_mercado_para_clases(p_clases jsonb, p_fecha date)
returns boolean
language sql immutable
as $$
    select coalesce(p_clases ? 'cripto', false)
        or (coalesce(p_clases ? 'accion', false) and extract(isodow from p_fecha) between 1 and 5)
$$;

-- ¿Cumple una señal las condiciones de una práctica? Mínimos inclusivos
-- y máximos EXCLUSIVOS, para que tramos contiguos no se solapen: el
-- tramo «ATR bajo» es `{max: 3}` y el «medio», `{min: 3, max: 6}`.
-- Una condición que no se puede comprobar (ATR nulo) no se cumple.
create function public.fn_cumple_condiciones(
    p_c jsonb, p_clase text, p_fuerza text, p_niveles text, p_atr numeric, p_rr numeric)
returns boolean
language sql immutable
as $$
    select coalesce(
           (p_c ->> 'clase' is null or p_c ->> 'clase' = p_clase)
       and (p_c -> 'fuerza' is null or p_c -> 'fuerza' ? coalesce(p_fuerza, ''))
       and (p_c ->> 'niveles_origen' is null or p_c ->> 'niveles_origen' = p_niveles)
       and (p_c #>> '{atr_pct,min}' is null or p_atr >= (p_c #>> '{atr_pct,min}')::numeric)
       and (p_c #>> '{atr_pct,max}' is null or p_atr <  (p_c #>> '{atr_pct,max}')::numeric)
       and (p_c #>> '{ratio_rr,min}' is null or p_rr >= (p_c #>> '{ratio_rr,min}')::numeric)
       and (p_c #>> '{ratio_rr,max}' is null or p_rr <  (p_c #>> '{ratio_rr,max}')::numeric),
       false)
$$;

-- Una práctica es adoptable por un agente solo si su predicado PUEDE
-- cumplirse con los parámetros de ese agente (desviación 6).
create function public.fn_practica_compatible(p_params jsonb, p_c jsonb)
returns boolean
language sql immutable
as $$
    select (p_c ->> 'clase' is null or p_params -> 'clases_admitidas' ? (p_c ->> 'clase'))
       and (p_c -> 'fuerza' is null or exists (
                select 1 from jsonb_array_elements_text(p_c -> 'fuerza') f
                 where p_params -> 'fuerzas_admitidas' ? f))
       and (p_c ->> 'niveles_origen' is null
            or p_params -> 'niveles_origen_admitidos' ? (p_c ->> 'niveles_origen'))
       and (p_c #>> '{ratio_rr,max}' is null
            or (p_c #>> '{ratio_rr,max}')::numeric > (p_params ->> 'rr_minimo')::numeric)
       and (p_c #>> '{atr_pct,max}' is null or p_params ->> 'atr_pct_min' is null
            or (p_c #>> '{atr_pct,max}')::numeric > (p_params ->> 'atr_pct_min')::numeric)
       and (p_c #>> '{atr_pct,min}' is null or p_params ->> 'atr_pct_max' is null
            or (p_c #>> '{atr_pct,min}')::numeric < (p_params ->> 'atr_pct_max')::numeric)
$$;

create function public.fn_rango_fuerza(p_fuerza text)
returns int
language sql immutable
as $$ select case p_fuerza when 'alta' then 3 when 'media' then 2 when 'baja' then 1 else 0 end $$;

-- P&L realizado de una cuenta en un día UTC (regla N8).
create function public.fn_pnl_realizado_dia(p_cuenta_id bigint, p_fecha date)
returns numeric
language sql stable
as $$
    select coalesce(sum(pnl_bruto), 0)
      from public.ordenes
     where cuenta_id = p_cuenta_id and estado = 'cerrada'
       and (fecha_salida at time zone 'UTC')::date = p_fecha
$$;

-- ═════════════════════════════════════════════════════════════════════
-- H-27 · Filtro de candidatos (doc 03 §5.1 pasos 5 y 6)
--
-- Devuelve TODO el universo con el motivo por el que cada señal queda
-- fuera, o NULL si es candidata. Los descartes no se tiran: son la
-- materia prima de tres disparadores del backlog y del racional.
--
-- El orden de los motivos importa: la dirección va ANTES que la
-- operabilidad porque una lectura bajista no es operable por diseño
-- (regla protegida nº2), y el disparador `sesgo_corto` necesita saber
-- que la señal cayó por la dirección y no por otra cosa.
-- ═════════════════════════════════════════════════════════════════════
create function public.fn_universo_agente(p_params jsonb, p_cuenta_id bigint, p_practicas jsonb)
returns table (
    senal_id bigint, activo_id bigint, simbolo text, clase text, fuerza text,
    niveles_origen text, ratio_rr numeric, atr_pct numeric, precio_actual numeric,
    sl numeric, tp numeric, leverage_recomendado numeric,
    alcistas int, bajistas int, antiguedad_min int, motivo text)
language sql stable
as $$
    select s.id, s.activo_id, s.simbolo, s.clase, s.fuerza, s.niveles_origen,
           s.ratio_rr, s.atr_pct, s.precio_actual, s.sl, s.tp, s.leverage_recomendado,
           s.indicadores_alcistas, s.indicadores_bajistas, x.antiguedad_min,
           case
               -- Una acción con la bolsa cerrada no está «añeja»: su dato
               -- del cierre es el último posible. Se separa para que el
               -- disparador de cadencia del ETL no salte cada noche.
               when x.antiguedad_min > (p_params ->> 'antiguedad_senal_max_min')::int
                    then case when s.clase = 'cripto' or public.fn_mercado_abierto(now())
                              then 'antiguedad' else 'fuera_de_sesion' end
               -- Regla protegida nº3: dominancia ESTRICTA; el empate excluye.
               when not (s.indicadores_alcistas > s.indicadores_bajistas) then 'direccion'
               when not s.operable and s.atr_pct is null then 'sin_atr'
               when not s.operable then 'no_operable'
               when not (p_params -> 'fuerzas_admitidas' ? coalesce(s.fuerza, '')) then 'fuerza'
               when not (p_params -> 'niveles_origen_admitidos' ? coalesce(s.niveles_origen, '')) then 'niveles_origen'
               when s.ratio_rr is null or s.ratio_rr < (p_params ->> 'rr_minimo')::numeric then 'rr'
               when p_params ->> 'atr_pct_min' is not null
                    and (s.atr_pct is null or s.atr_pct < (p_params ->> 'atr_pct_min')::numeric) then 'atr_bajo'
               when p_params ->> 'atr_pct_max' is not null
                    and (s.atr_pct is null or s.atr_pct > (p_params ->> 'atr_pct_max')::numeric) then 'atr_alto'
               when exists (select 1 from public.ordenes o
                             where o.cuenta_id = p_cuenta_id and o.activo_id = s.activo_id
                               and o.estado = 'abierta') then 'posicion_abierta'
               -- Paso 6: las prácticas adoptadas, al final. Así «qué habría
               -- entrado sin ellas» es exactamente lo que tiene motivo
               -- NULL o 'practica', y el efecto de adoptar es medible.
               when exists (select 1 from jsonb_array_elements(coalesce(p_practicas, '[]'::jsonb)) c
                             where not public.fn_cumple_condiciones(
                                 c, s.clase, s.fuerza, s.niveles_origen, s.atr_pct, s.ratio_rr))
                    then 'practica'
           end
      from public.senales_vigentes s
      cross join lateral (
           select round(extract(epoch from now() - s.calculado_en) / 60)::int as antiguedad_min) x
     where s.estado_activo = 'activo'
       and p_params -> 'clases_admitidas' ? s.clase
$$;

-- ═════════════════════════════════════════════════════════════════════
-- H-27 · La decisión, sin efectos
--
-- Todo lo que el ciclo decide sale de aquí, y esta función no escribe
-- nada. Es lo que hace comprobable el criterio «reejecutar el ciclo con
-- el mismo estado produce la misma decisión»: se llama dos veces y se
-- comparan los dos JSON. Y lo que hace reproducible un mal día de
-- Audacia: con el mismo estado, la misma respuesta.
-- ═════════════════════════════════════════════════════════════════════
create function public.fn_decidir_agente(p_agente_id bigint)
returns jsonb
language plpgsql stable
security definer
set search_path = public, pg_temp
as $$
declare
    v_ag         public.agentes;
    v_p          jsonb;
    v_cuenta     public.cuentas_simulacion;
    v_hoy        date := (now() at time zone 'UTC')::date;
    v_equity     numeric;
    v_objetivo   numeric;
    v_logrado    numeric;
    v_deficit    numeric;
    v_abiertas   int;
    v_margen_pct numeric;
    v_tope       numeric;
    v_propio     numeric;
    v_riesgo     numeric;
    v_practicas  jsonb;
    v_ids_pract  jsonb;
    v_base       jsonb;
    v_universo   int;
    v_frescas    int;
    v_sin_alc    boolean;
    v_antes      int;
    v_cands      jsonb;
    v_descartes  jsonb;
    v_top3       jsonb;
begin
    select * into v_ag from public.agentes where id = p_agente_id;
    select * into v_cuenta from public.cuentas_simulacion where id = public.fn_cuenta_agente(p_agente_id);
    v_p := public.fn_parametros_agente(v_ag);

    v_equity := public.fn_equity(v_cuenta.id);
    select objetivo_importe into v_objetivo from public.agente_dias
     where agente_id = p_agente_id and fecha = v_hoy;
    v_objetivo := coalesce(v_objetivo, round(v_equity * v_ag.objetivo_diario_pct / 100, 2));
    v_logrado  := public.fn_pnl_realizado_dia(v_cuenta.id, v_hoy);
    v_deficit  := v_objetivo - v_logrado;

    v_base := jsonb_build_object(
        'agente', v_ag.nombre, 'cuenta_id', v_cuenta.id,
        'version_estrategia', v_ag.version_estrategia,
        'equity', round(v_equity, 2), 'objetivo_importe', v_objetivo,
        'logrado', v_logrado, 'deficit_pendiente', round(v_deficit, 2));

    -- ── Paso 3 · N9: meta cumplida ⇒ modo conservación ───────────────
    if v_deficit <= 0 then
        return v_base || jsonb_build_object('accion', 'meta_cumplida');
    end if;

    -- ── Paso 4 · ¿hay hueco? ─────────────────────────────────────────
    select count(*) into v_abiertas
      from public.ordenes where cuenta_id = v_cuenta.id and estado = 'abierta';
    if v_abiertas >= (v_p ->> 'max_posiciones_abiertas')::int then
        return v_base || jsonb_build_object('accion', 'sin_hueco', 'abiertas', v_abiertas);
    end if;
    v_margen_pct := case when v_equity > 0 then v_cuenta.saldo_bloqueado / v_equity * 100 else 100 end;
    if v_margen_pct >= (v_p ->> 'margen_comprometido_max_pct')::numeric then
        return v_base || jsonb_build_object('accion', 'margen_lleno',
                                            'margen_comprometido_pct', round(v_margen_pct, 2));
    end if;

    -- ── Pasos 5 y 6 · filtro y prácticas ─────────────────────────────
    select coalesce(jsonb_agg(p.condiciones order by p.id), '[]'::jsonb),
           coalesce(jsonb_agg(p.id order by p.id), '[]'::jsonb)
      into v_practicas, v_ids_pract
      from public.mp_adopciones ad
      join public.mejores_practicas p on p.id = ad.practica_id
     where ad.agente_id = p_agente_id and ad.abandonada_en is null
       and p.estado in ('propuesta', 'validada');

    v_tope   := public.fn_tope_fase(v_cuenta.fase);
    v_propio := (v_p ->> 'apalancamiento_maximo_propio')::numeric;
    v_riesgo := (v_p ->> 'riesgo_pct_operacion')::numeric;

    with u as (
        select * from public.fn_universo_agente(v_p, v_cuenta.id, v_practicas)
    ),
    dim as (
        -- Paso 8, en el orden del paso 7: el dimensionado de cada
        -- candidato con los mismos topes que aplicará `rpc_abrir_orden`.
        select u.*, d.cantidad, d.apalancamiento, d.margen, d.precio_liquidacion,
               d.motivo as motivo_dim,
               least(coalesce(u.leverage_recomendado, v_tope), v_propio, v_tope) as lev_pedido
          from u
          cross join lateral public.fn_dimensionar_posicion(
               v_equity, v_cuenta.saldo_disponible, v_cuenta.saldo_bloqueado,
               u.precio_actual, u.sl, v_riesgo,
               (v_p ->> 'margen_comprometido_max_pct')::numeric,
               least(coalesce(u.leverage_recomendado, v_tope), v_propio, v_tope),
               v_propio, v_tope) d
         where u.motivo is null
    ),
    ordenados as (
        -- Paso 7: cuatro claves. La cuarta, el símbolo, existe para que un
        -- empate no lo gane quien llegue antes en la consulta.
        select dim.*,
               row_number() over (order by ratio_rr desc,
                                           public.fn_rango_fuerza(fuerza) desc,
                                           (alcistas - bajistas) desc,
                                           simbolo asc) as puesto
          from dim
    )
    select coalesce(jsonb_agg(jsonb_build_object(
               'senal_id', senal_id, 'activo_id', activo_id, 'simbolo', simbolo,
               'clase', clase, 'fuerza', fuerza, 'niveles_origen', niveles_origen,
               'ratio_rr', round(ratio_rr, 4), 'atr_pct', atr_pct,
               'dominancia_neta', alcistas - bajistas, 'puesto', puesto,
               'apalancamiento_pedido', lev_pedido,
               'apalancamiento', apalancamiento, 'margen', margen,
               'cantidad', cantidad, 'precio_liquidacion', round(precio_liquidacion, 8),
               'descarte', case when motivo_dim is not null then 'dimensionado:' || motivo_dim
                                when margen < 10 then 'margen_minimo' end)
               order by puesto), '[]'::jsonb)
      into v_cands
      from ordenados;

    select count(*),
           count(*) filter (where motivo is distinct from 'fuera_de_sesion'
                              and motivo is distinct from 'antiguedad'),
           count(*) filter (where motivo is null or motivo = 'practica')
      into v_universo, v_frescas, v_antes
      from public.fn_universo_agente(v_p, v_cuenta.id, v_practicas);

    -- Un ciclo «sin alcistas»: había señales frescas y TODAS cayeron por
    -- la dirección. Es la unidad del disparador `sesgo_corto`.
    select v_frescas > 0 and bool_and(motivo = 'direccion')
      into v_sin_alc
      from public.fn_universo_agente(v_p, v_cuenta.id, v_practicas)
     where motivo is distinct from 'fuera_de_sesion' and motivo is distinct from 'antiguedad';

    select coalesce(jsonb_object_agg(m, n), '{}'::jsonb) into v_descartes
      from (select coalesce(motivo, 'candidata') as m, count(*) as n
              from public.fn_universo_agente(v_p, v_cuenta.id, v_practicas)
             group by 1) t;

    select coalesce(jsonb_agg(jsonb_build_object(
               'simbolo', simbolo, 'motivo', motivo, 'ratio_rr', round(ratio_rr, 4),
               'fuerza', fuerza) order by ratio_rr desc nulls last, simbolo), '[]'::jsonb)
      into v_top3
      from (select * from public.fn_universo_agente(v_p, v_cuenta.id, v_practicas)
             where motivo is not null
               and motivo not in ('fuera_de_sesion', 'antiguedad')
             order by ratio_rr desc nulls last, simbolo
             limit 3) t;

    v_base := v_base || jsonb_build_object(
        'candidatos_evaluados', jsonb_array_length(v_cands),
        'candidatos_antes_practicas', v_antes,
        'candidatos', v_cands,
        'descartados_top3', v_top3,
        'descartes_por_motivo', v_descartes,
        'practicas_aplicadas', v_ids_pract,
        'universo', v_universo,
        'frescas', v_frescas,
        'sin_alcistas', coalesce(v_sin_alc, false),
        'parametros', v_p);

    -- «Sin candidatos» es una salida de primera clase: no se relaja ningún
    -- criterio para forzar una operación (igual que en rotacion.py).
    if not exists (select 1 from jsonb_array_elements(v_cands) c where c ->> 'descarte' is null) then
        return v_base || jsonb_build_object('accion', 'sin_candidatos');
    end if;
    return v_base || jsonb_build_object('accion', 'abrir');
end;
$$;

-- ═════════════════════════════════════════════════════════════════════
-- H-27 · El día del agente (doc 03 §5.2)
-- ═════════════════════════════════════════════════════════════════════
create function public.fn_cerrar_dia_agente(p_agente_id bigint, p_fecha date, p_equity numeric)
returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_dia public.agente_dias;
begin
    select * into v_dia from public.agente_dias
     where agente_id = p_agente_id and fecha = p_fecha and cerrado_en is null
       for update;
    if not found then return; end if;

    update public.agente_dias d set
        saldo_cierre    = round(p_equity, 2),
        pnl_realizado   = x.pnl,
        rendimiento_pct = case when d.saldo_apertura > 0
                               then round((p_equity / d.saldo_apertura - 1) * 100, 4) end,
        -- N8: sobre P&L realizado. Y solo en un día operable.
        cumplido        = d.operable and x.pnl >= d.objetivo_importe,
        ops_abiertas    = x.abiertas,
        ops_cerradas    = x.cerradas,
        ops_tp          = x.tp,
        ops_sl          = x.sl,
        cerrado_en      = now()
      from (
        select public.fn_pnl_realizado_dia(v_dia.cuenta_id, p_fecha) as pnl,
               count(*) filter (where (fecha_entrada at time zone 'UTC')::date = p_fecha) as abiertas,
               count(*) filter (where estado = 'cerrada'
                                  and (fecha_salida at time zone 'UTC')::date = p_fecha) as cerradas,
               count(*) filter (where motivo_cierre = 'tp'
                                  and (fecha_salida at time zone 'UTC')::date = p_fecha) as tp,
               count(*) filter (where motivo_cierre in ('sl', 'liquidacion')
                                  and (fecha_salida at time zone 'UTC')::date = p_fecha) as sl
          from public.ordenes where cuenta_id = v_dia.cuenta_id
      ) x
     where d.agente_id = p_agente_id and d.fecha = p_fecha;
end;
$$;

-- Paso 1. Si el día ya existe, no hace nada. Si es nuevo, cierra lo que
-- quedara abierto y abre el de hoy con el MISMO equity: por eso
-- `saldo_apertura` de hoy coincide al céntimo con `saldo_cierre` de ayer.
create function public.fn_sincronizar_dia_agente(p_agente_id bigint, p_cuenta_id bigint)
returns public.agente_dias
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_hoy    date := (now() at time zone 'UTC')::date;
    v_dia    public.agente_dias;
    v_ag     public.agentes;
    v_equity numeric;
    v_f      date;
begin
    select * into v_dia from public.agente_dias where agente_id = p_agente_id and fecha = v_hoy;
    if found then return v_dia; end if;

    select * into v_ag from public.agentes where id = p_agente_id;
    v_equity := round(public.fn_equity(p_cuenta_id), 2);

    for v_f in select fecha from public.agente_dias
                where agente_id = p_agente_id and fecha < v_hoy and cerrado_en is null
                order by fecha
    loop
        perform public.fn_cerrar_dia_agente(p_agente_id, v_f, v_equity);
    end loop;

    insert into public.agente_dias
        (agente_id, fecha, cuenta_id, saldo_apertura, objetivo_importe, operable)
    values (p_agente_id, v_hoy, p_cuenta_id, v_equity,
            round(v_equity * v_ag.objetivo_diario_pct / 100, 2),
            -- Desviación 5: un agente en pausa no tiene días operables.
            v_ag.estado in ('activo', 'cuarentena')
            and public.fn_mercado_para_clases(
                    public.fn_parametros_agente(v_ag) -> 'clases_admitidas', v_hoy))
    on conflict do nothing
    returning * into v_dia;

    if v_dia.agente_id is null then
        select * into v_dia from public.agente_dias where agente_id = p_agente_id and fecha = v_hoy;
    end if;
    return v_dia;
end;
$$;

-- ═════════════════════════════════════════════════════════════════════
-- H-30 · Backlog autónomo (doc 03 §8)
-- ═════════════════════════════════════════════════════════════════════

-- Inserta o suma. Devuelve true si la fila es nueva. Una ocurrencia es
-- un par (agente, día): la segunda vez que el mismo agente dispara la
-- misma clave el mismo día no cuenta (desviación 3).
create function public.fn_registrar_backlog(
    p_agente_id bigint, p_tipo text, p_clave text, p_titulo text,
    p_descripcion text, p_justificacion text, p_evidencia jsonb, p_prioridad int)
returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_id    bigint;
    v_hoy   date := (now() at time zone 'UTC')::date;
    v_nuevo boolean := false;
begin
    insert into public.agente_backlog
        (agente_id, tipo, titulo, descripcion, justificacion, evidencia,
         clave_deduplicacion, agentes_solicitantes, prioridad_sugerida)
    values (p_agente_id, p_tipo, p_titulo, p_descripcion, p_justificacion, p_evidencia,
            p_clave, array[p_agente_id], p_prioridad)
    on conflict (tipo, clave_deduplicacion) do nothing
    returning id into v_id;

    if v_id is not null then
        v_nuevo := true;
        insert into public.agente_backlog_ocurrencias (backlog_id, agente_id, fecha)
        values (v_id, p_agente_id, v_hoy);
        insert into public.eventos_sistema (agente_id, tipo, mensaje, datos)
        values (p_agente_id, 'backlog_nuevo',
                (select nombre from public.agentes where id = p_agente_id) || ' pide: ' || p_titulo,
                jsonb_build_object('backlog_id', v_id, 'tipo', p_tipo, 'clave', p_clave));
        return true;
    end if;

    select id into v_id from public.agente_backlog
     where tipo = p_tipo and clave_deduplicacion = p_clave;

    insert into public.agente_backlog_ocurrencias (backlog_id, agente_id, fecha)
    values (v_id, p_agente_id, v_hoy)
    on conflict do nothing;
    if found then
        update public.agente_backlog
           set ocurrencias = ocurrencias + 1,
               agentes_solicitantes = case when p_agente_id = any(agentes_solicitantes)
                                           then agentes_solicitantes
                                           else agentes_solicitantes || p_agente_id end,
               evidencia = p_evidencia,
               actualizado_en = now()
         where id = v_id;
    end if;
    return false;
end;
$$;

-- Los siete disparadores deterministas. Cada uno observa una limitación
-- real y deja evidencia con identificadores concretos.
create function public.fn_disparadores_backlog(p_agente_id bigint, p_decision jsonb)
returns int
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_ag      public.agentes;
    v_p       jsonb;
    v_cuenta  public.cuentas_simulacion;
    v_hoy     date := (now() at time zone 'UTC')::date;
    v_dia     public.agente_dias;
    v_n       int := 0;
    v_fechas  jsonb;
    v_ids     jsonb;
    v_mov     numeric;
    v_r       record;
begin
    select * into v_ag from public.agentes where id = p_agente_id;
    select * into v_cuenta from public.cuentas_simulacion where id = public.fn_cuenta_agente(p_agente_id);
    select * into v_dia from public.agente_dias where agente_id = p_agente_id and fecha = v_hoy;
    v_p := public.fn_parametros_agente(v_ag);

    -- 1. Sin candidatos por dirección: los tres últimos días con señales
    --    frescas, todos con cada ciclo «sin alcistas».
    select jsonb_agg(fecha order by fecha) into v_fechas
      from (select fecha, ciclos_con_universo, ciclos_sin_alcistas
              from public.agente_dias
             where agente_id = p_agente_id and ciclos_con_universo > 0
             order by fecha desc limit 3) t
    having count(*) = 3 and bool_and(ciclos_sin_alcistas = ciclos_con_universo);
    if v_fechas is not null then
        perform public.fn_registrar_backlog(p_agente_id, 'sesgo_corto', 'sesgo_corto:global',
            'Operar en corto',
            'Tres días seguidos en los que ninguna señal fresca tuvo más indicadores alcistas que bajistas.',
            'Solo-largo es la regla protegida nº2 (D6). Esta entrada mide cuánto cuesta: días enteros sin ninguna operación posible.',
            jsonb_build_object('dias', v_fechas, 'agente', v_ag.nombre), 3);
        v_n := v_n + 1;
    end if;

    -- 2. Universo insuficiente: cinco ciclos de hoy sin candidatos.
    if coalesce(v_dia.ciclos_sin_candidatos, 0) >= 5 then
        perform public.fn_registrar_backlog(p_agente_id, 'nuevo_activo', 'nuevo_activo:universo',
            'Ampliar el universo de activos',
            format('%s ciclos de hoy sin ningún candidato que pase el filtro de %s.',
                   v_dia.ciclos_sin_candidatos, v_ag.nombre),
            'Los descartes muestran por qué criterio cae cada señal; si ninguno encaja, faltan activos con ese perfil.',
            jsonb_build_object('fecha', v_hoy, 'ciclos_sin_candidatos', v_dia.ciclos_sin_candidatos,
                               'descartes', v_dia.descartes), 2);
        v_n := v_n + 1;
    end if;

    -- 3. Tope de fase estrangulando (doc 03 §1.4): movimiento del
    --    subyacente que exige la meta con el tope de Fase 2 y el margen
    --    máximo del agente.
    if v_cuenta.fase = 'fase_2_consolidacion' then
        v_mov := v_ag.objetivo_diario_pct
                 / (public.fn_tope_fase(v_cuenta.fase)
                    * (v_p ->> 'margen_comprometido_max_pct')::numeric / 100);
        if v_mov > 3 then
            perform public.fn_registrar_backlog(p_agente_id, 'reversion_fase',
                'reversion_fase:cuenta_' || v_cuenta.id,
                'Revisar el umbral de la Fase 2',
                format('Con tope %sx y %s %% de margen, la meta de %s %% exige un %s %% diario del subyacente.',
                       public.fn_tope_fase(v_cuenta.fase), v_p ->> 'margen_comprometido_max_pct',
                       v_ag.objetivo_diario_pct, round(v_mov, 2)),
                'Volver a Fase 1 exige acción humana (regla protegida nº5). Esta entrada es el dato para decidir si la Fase 3 cambia el umbral.',
                jsonb_build_object('cuenta_id', v_cuenta.id, 'fase', v_cuenta.fase,
                                   'objetivo_diario_pct', v_ag.objetivo_diario_pct,
                                   'margen_max_pct', v_p -> 'margen_comprometido_max_pct',
                                   'movimiento_exigido_pct', round(v_mov, 2)), 4);
            v_n := v_n + 1;
        end if;
    end if;

    -- 4. Volatilidad no disponible: el mismo activo, cinco señales sin
    --    ATR en la última semana.
    for v_r in
        select a.id, a.simbolo, count(*) as n, jsonb_agg(s.id order by s.id desc) as ids
          from public.senales s join public.activos a on a.id = s.activo_id
         where s.atr_pct is null and not s.operable
           and s.calculado_en > now() - interval '7 days'
           and v_p -> 'clases_admitidas' ? a.clase
         group by a.id, a.simbolo
        having count(*) >= 5
    loop
        perform public.fn_registrar_backlog(p_agente_id, 'nuevo_dato', 'nuevo_dato:atr:' || v_r.simbolo,
            'Volatilidad de ' || v_r.simbolo,
            format('%s señales de %s sin ATR en siete días: el activo no es operable.', v_r.n, v_r.simbolo),
            'Sin volatilidad conocida no se opera (regla protegida nº4). Falta el dato, no el criterio.',
            jsonb_build_object('activo_id', v_r.id, 'simbolo', v_r.simbolo, 'senales', v_r.n,
                               'ultimas', (select jsonb_agg(value) from (
                                   select value from jsonb_array_elements(v_r.ids) limit 5) t)), 2);
        v_n := v_n + 1;
    end loop;

    -- 5. Cierre parcial: tres stops que antes tocaron el 80 % del camino al TP.
    select jsonb_agg(o.id order by o.id) into v_ids
      from public.ordenes o join public.cuentas_simulacion c on c.id = o.cuenta_id
     where c.agente_id = p_agente_id and o.motivo_cierre in ('sl', 'liquidacion')
       and o.precio_max_visto >= o.precio_entrada + 0.8 * (o.tp - o.precio_entrada)
    having count(*) >= 3;
    if v_ids is not null then
        perform public.fn_registrar_backlog(p_agente_id, 'nueva_herramienta',
            'nueva_herramienta:cierre_parcial', 'Cierre parcial',
            format('%s operaciones llegaron al 80 %% del recorrido hasta el objetivo y acabaron en el stop.',
                   jsonb_array_length(v_ids)),
            'Con cierre parcial, parte de ese recorrido habría quedado asegurado.',
            jsonb_build_object('ordenes', v_ids), 3);
        v_n := v_n + 1;
    end if;

    -- 6. Trailing stop: tres cierres en TP tras los que el precio subió
    --    más de un 2 % en las 24 h siguientes.
    select jsonb_agg(o.id order by o.id) into v_ids
      from public.ordenes o join public.cuentas_simulacion c on c.id = o.cuenta_id
     where c.agente_id = p_agente_id and o.motivo_cierre = 'tp'
       and o.precio_max_post_cierre > o.tp * 1.02
    having count(*) >= 3;
    if v_ids is not null then
        perform public.fn_registrar_backlog(p_agente_id, 'nueva_herramienta',
            'nueva_herramienta:trailing_stop', 'Trailing stop',
            format('%s cierres en objetivo tras los que el precio siguió subiendo más de un 2 %%.',
                   jsonb_array_length(v_ids)),
            'Un stop que sigue al precio habría capturado parte de esa subida.',
            jsonb_build_object('ordenes', v_ids), 3);
        v_n := v_n + 1;
    end if;

    -- 7. Señal añeja: diez descartes hoy por antigüedad, con mercado abierto.
    if coalesce((v_dia.descartes ->> 'antiguedad')::int, 0) >= 10 then
        perform public.fn_registrar_backlog(p_agente_id, 'ajuste_regla', 'ajuste_regla:cadencia_etl',
            'Señales más frecuentes',
            format('%s descartes hoy por señales de más de %s minutos con el mercado abierto.',
                   v_dia.descartes ->> 'antiguedad', v_p ->> 'antiguedad_senal_max_min'),
            'La cadencia del ETL limita lo que el agente puede operar.',
            jsonb_build_object('fecha', v_hoy, 'descartes_antiguedad', v_dia.descartes -> 'antiguedad',
                               'antiguedad_max_min', v_p -> 'antiguedad_senal_max_min'), 2);
        v_n := v_n + 1;
    end if;

    return v_n;
end;
$$;

