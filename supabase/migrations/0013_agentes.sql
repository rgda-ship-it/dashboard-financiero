      join public.agentes g on g.id = c.agente_id
      join public.activos a on a.id = o.activo_id;

-- La curva real y la teórica `saldo_inicial × (1+p)^n`, con n = días
-- operables transcurridos. La teórica es una referencia visual, no un
-- cálculo que alimente ninguna decisión (doc 03 §5.2).
create view public.v_curva_agentes
with (security_invoker = true) as
    select d.agente_id, g.nombre, d.cuenta_id, d.fecha, d.operable, d.cumplido,
           d.saldo_apertura, d.saldo_cierre, d.objetivo_importe, d.pnl_realizado,
           round(c.saldo_inicial * power(1 + g.objetivo_diario_pct / 100,
                 count(*) filter (where d.operable)
                     over (partition by d.cuenta_id order by d.fecha)), 2) as saldo_teorico
      from public.agente_dias d
      join public.agentes g on g.id = d.agente_id
      join public.cuentas_simulacion c on c.id = d.cuenta_id;

-- Lo que los agentes piden, con la prioridad del doc 03 §8:
-- ocurrencias × número de agentes distintos que lo piden.
create view public.v_backlog_priorizado
with (security_invoker = true) as
    select b.*,
           b.ocurrencias * cardinality(b.agentes_solicitantes) as prioridad,
           (select array_agg(g.nombre order by g.id) from public.agentes g
             where g.id = any(b.agentes_solicitantes)) as solicitantes
      from public.agente_backlog b
     order by b.ocurrencias * cardinality(b.agentes_solicitantes) desc,
              b.prioridad_sugerida desc nulls last, b.id;

