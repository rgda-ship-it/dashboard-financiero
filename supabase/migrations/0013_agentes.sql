create table public.agentes (
    id                   bigint generated by default as identity primary key,
    nombre               text not null unique,
    objetivo_diario_pct  numeric(5, 2) not null check (objetivo_diario_pct > 0 and objetivo_diario_pct <= 50),
    objetivo_final       numeric(20, 2) not null default 1000000,
    saldo_inicial        numeric(20, 2) not null default 500 check (saldo_inicial > 0),
    -- Todo parámetro operativo vive aquí (doc 03 §3.2), nunca en código
    -- ni en variables de entorno: deuda técnica nº3 de la Fase 1.
    estrategia           jsonb not null check (jsonb_typeof(estrategia) = 'object'),
    version_estrategia   int not null default 1,
    estado               text not null default 'pausado'
                         check (estado in ('activo', 'cuarentena', 'pausado', 'game_over')),
    -- Al pausar se recuerda de dónde venía: reanudar a un agente en
    -- cuarentena no puede ser una forma de sacarlo de ella.
    estado_previo        text check (estado_previo in ('activo', 'cuarentena')),
    -- Consecuencia de una semana deficiente (doc 03 §6.2). Desviación 4.
    riesgo_reducido      boolean not null default false,
    destilado_en         timestamptz,
    creado_en            timestamptz not null default now(),
    game_over_en         timestamptz
);

