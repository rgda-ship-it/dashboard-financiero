-- ─────────────────────────────────────────────────────────────────────
-- 0013 — Agentes, corte semanal, prácticas, backlog y eventos en tiempo
-- real (Sprint 6, H-27…H-33).
--
-- Lo que esta migración añade, en una frase: tres agentes deterministas
-- operan solos con cuentas de 500 $, un corte semanal les pone nota con
-- consecuencias, comparten lo que les funciona y piden lo que les falta.
--
-- CUATRO DECISIONES DEL DUEÑO (2026-09-29)
--
-- D11 — EL CICLO Y EL CORTE SON SQL SOBRE `pg_cron`, NO EDGE FUNCTIONS.
--   Mismo razonamiento que D8 para el monitor: una Edge Function queda
--   fuera de la única validación automática del proyecto (aplicar las
--   migraciones sobre un PostgreSQL limpio y correr las invariantes) y
--   exige un despliegue manual en cada cambio. En SQL, los diez pasos
--   del doc 03 §5.1 se prueban en cada pull request. Y el agente no
--   necesita nada que PostgreSQL no tenga: el doc 03 §2 ya exigía «cero
--   llamadas a APIs externas» en el ciclo.
--
-- D12 — EL UNIVERSO DE LOS AGENTES ES TODO EL CATÁLOGO ACTIVO. No tienen
--   cartera: miran `senales_vigentes` de cualquier activo en estado
--   'activo'. Consecuencia: el universo crece cuando un usuario da de
--   alta un activo, y eso es parte del experimento, no un ruido.
--
-- D13 — LOS AGENTES NACEN EN PAUSA. Se crean con sus cuentas de 500 $ en
--   estado 'pausado' y los pone en marcha un administrador desde /admin
--   (`rpc_cambiar_estado_agente`, auditado). Aplicar una migración no
--   debe ser lo que abre la primera orden en producción.
--
-- D14 — UN SOLO PULL REQUEST para el sprint, como el Sprint 5.
--
-- DESVIACIONES DEL DISEÑO, CON MOTIVO
--
--   1. El corte semanal corre los LUNES a las 00:07 UTC sobre la semana
--      ISO que acaba de terminar, no el domingo a las 23:59. A las 23:59
--      del domingo el día aún no está cerrado: las órdenes que cierren
--      en el último minuto quedarían fuera de su día. A las 00:07 el
--      ciclo de las 00:00 y el de las 00:05 ya cerraron el domingo.
--   2. Un dimensionado por debajo de 10 $ de margen DESCARTA el candidato
--      en vez de marcar la cuenta 'inoperante' (doc 03 §5.1 paso 8). Ese
--      margen pequeño suele venir de G3 —queda poco margen libre—, no de
--      una ruina; y `rpc_evaluar_game_over` devolvería la cuenta a
--      'activa' en el ciclo siguiente, así que el estado parpadearía. La
--      ruina técnica la sigue declarando `rpc_evaluar_game_over`.
--   3. `ocurrencias` del backlog cuenta pares (agente, día), no ciclos.
--      Con un ciclo cada 5 minutos, «ocurrencias = 288» significaría «un
--      día»: el número mediría la cadencia del cron, no la insistencia
--      del problema. Contado por días, 3 agentes × 20 días = 60 se lee
--      solo.
--   4. Tras una semana deficiente el riesgo queda a la mitad HASTA la
--      siguiente 'validada' (criterio de aceptación de H-28), no «durante
--      la semana siguiente» (doc 03 §6.2). Las dos frases se contradicen
--      y manda el criterio de aceptación. No se acumula: dos deficientes
--      seguidas no lo dejan en un cuarto, lo dejan en cuarentena.
--   5. Un día cuenta como operable solo si el agente estaba en marcha. Un
--      agente en pausa no suspende el corte por calendario administrativo,
--      igual que Prudencia no lo suspende por el fin de semana (N10).
--   6. Solo se adoptan prácticas COMPATIBLES con el perfil: una práctica
--      de cripto adoptada por Prudencia, que solo opera acciones, la
--      dejaría sin ningún candidato, y el «efecto medido» sería un
--      artefacto.
--   7. En la evaluación de adopciones, «mejoró» es superar al antes en un
--      10 % de su valor ABSOLUTO. `despues > antes × 1,1` (doc 03 §7.2)
--      invierte el sentido cuando el rendimiento previo es negativo:
--      pasar de −2 % a −2,1 % saldría «mejoró».
-- ─────────────────────────────────────────────────────────────────────

