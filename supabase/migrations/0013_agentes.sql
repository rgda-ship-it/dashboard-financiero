-- Poner en marcha o pausar (D13). Siempre auditado.
create function public.rpc_cambiar_estado_agente(p_agente_id bigint, p_estado text)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_ag    public.agentes;
    v_nuevo text;
    v_hoy   date := (now() at time zone 'UTC')::date;
begin
    if not public.es_admin() then
        raise exception 'Solo un administrador puede poner en marcha o pausar un agente.' using errcode = '42501';
    end if;
    if p_estado not in ('activo', 'pausado') then
        raise exception 'Estado no válido: % (activo | pausado)', p_estado using errcode = '22023';
    end if;
    select * into v_ag from public.agentes where id = p_agente_id for update;
    if not found then
        raise exception 'El agente % no existe', p_agente_id using errcode = 'P0002';
    end if;
    if v_ag.estado = 'game_over' then
        raise exception '% está en Game Over: reinícialo, no se reanuda.', v_ag.nombre using errcode = 'P0001';
    end if;

    if p_estado = 'pausado' then
        if v_ag.estado = 'pausado' then return jsonb_build_object('estado', 'pausado', 'cambio', false); end if;
        update public.agentes set estado = 'pausado', estado_previo = v_ag.estado where id = p_agente_id;
        -- El día en curso deja de contar, salvo que ya estuviera cumplido.
        update public.agente_dias set operable = false
         where agente_id = p_agente_id and fecha = v_hoy and cerrado_en is null and not cumplido;
        v_nuevo := 'pausado';
    else
        if v_ag.estado <> 'pausado' then return jsonb_build_object('estado', v_ag.estado, 'cambio', false); end if;
        v_nuevo := coalesce(v_ag.estado_previo, 'activo');
        update public.agentes set estado = v_nuevo, estado_previo = null where id = p_agente_id;
        update public.agente_dias
           set operable = public.fn_mercado_para_clases(
                   public.fn_parametros_agente(v_ag) -> 'clases_admitidas', v_hoy)
         where agente_id = p_agente_id and fecha = v_hoy and cerrado_en is null;
    end if;

    insert into public.auditoria_admin (actor_id, accion, objetivo_tipo, objetivo_id, detalle)
    values (auth.uid(), 'cambiar_estado_agente', 'agente', p_agente_id::text,
            jsonb_build_object('de', v_ag.estado, 'a', v_nuevo, 'agente', v_ag.nombre));
    insert into public.eventos_sistema (agente_id, tipo, mensaje, datos)
    values (p_agente_id, 'agente',
            v_ag.nombre || case when v_nuevo = 'pausado' then ' queda en pausa' else ' se pone en marcha' end,
            jsonb_build_object('de', v_ag.estado, 'a', v_nuevo));
    return jsonb_build_object('estado', v_nuevo, 'cambio', true);
end;
$$;

-- Regla N14: un Game Over no se revierte. Reiniciar crea una cuenta
-- NUEVA y conserva la anterior entera, que es el dato más valioso del
-- experimento. El agente vuelve en pausa (D13).
create function public.rpc_reiniciar_agente(p_agente_id bigint, p_confirmacion boolean)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_ag     public.agentes;
    v_previa bigint;
    v_cuenta bigint;
begin
    if not public.es_admin() then
        raise exception 'Solo un administrador puede reiniciar un agente.' using errcode = '42501';
    end if;
    if p_confirmacion is not true then
        raise exception 'Reiniciar un agente exige confirmación explícita.' using errcode = 'P0001';
    end if;
    select * into v_ag from public.agentes where id = p_agente_id for update;
    if not found then
        raise exception 'El agente % no existe', p_agente_id using errcode = 'P0002';
    end if;
    if v_ag.estado <> 'game_over' then
        raise exception '% no está en Game Over: no hay nada que reiniciar.', v_ag.nombre using errcode = 'P0001';
    end if;

    v_previa := public.fn_cuenta_agente(p_agente_id);
    update public.agentes set estado = 'pausado', estado_previo = null, riesgo_reducido = false
     where id = p_agente_id;
    v_cuenta := public.fn_crear_cuenta_agente(p_agente_id);

    insert into public.auditoria_admin (actor_id, accion, objetivo_tipo, objetivo_id, detalle)
    values (auth.uid(), 'reiniciar_agente', 'agente', p_agente_id::text,
            jsonb_build_object('agente', v_ag.nombre, 'cuenta_anterior', v_previa, 'cuenta_nueva', v_cuenta));
    insert into public.eventos_sistema (agente_id, tipo, mensaje, datos)
    values (p_agente_id, 'agente', v_ag.nombre || ' reiniciado con una cuenta nueva',
            jsonb_build_object('cuenta_anterior', v_previa, 'cuenta_id', v_cuenta));
    return jsonb_build_object('cuenta_anterior', v_previa, 'cuenta_nueva', v_cuenta);
end;
$$;

-- Revisión humana del backlog (H-30).
create function public.rpc_revisar_backlog(p_id bigint, p_estado text, p_resolucion text default null)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
    v_previo text;
begin
    if not public.es_admin() then
        raise exception 'Solo un administrador revisa el backlog de los agentes.' using errcode = '42501';
    end if;
    if p_estado not in ('en_revision', 'aceptado', 'rechazado', 'implementado') then
